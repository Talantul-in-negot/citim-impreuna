// Rulează 20261111_01 pe PostgreSQL real (PGlite): pe o schemă ca cea live (FK-uri
// NO ACTION) ștergerea unui utilizator cu date eșuează, iar după migrare reușește
// și șterge în cascadă; reaplicarea și schema nouă (deja cascade) sunt sigure.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { PGlite } = require(process.env.CI_PGLITE_MODULE || '@electric-sql/pglite');

const migration = fs.readFileSync(path.join(__dirname, '..', 'supabase', '20261111_01_events_scores_fk_cascade.sql'), 'utf8');
const A = '00000000-0000-0000-0000-00000000000a';
const B = '00000000-0000-0000-0000-00000000000b';

async function schema(onDelete, { namedLikeLive }) {
  const db = new PGlite();
  const fk = (name) => `constraint ${name} foreign key (user_id) references auth.users(id) ${onDelete}`;
  await db.exec(`
    create schema auth;
    create table auth.users(id uuid primary key, email text);
    create table public.events(id bigint generated by default as identity primary key, user_id uuid, verse_ref text,
      ${fk(namedLikeLive ? 'events_user_id_fkey' : 'weird_events_fk')});
    create table public.scores(user_id uuid primary key, points integer default 0,
      ${fk(namedLikeLive ? 'scores_user_id_fkey' : 'weird_scores_fk')});
    insert into auth.users values ('${A}', 'a@x'), ('${B}', 'b@x');
    insert into public.events(user_id, verse_ref) values ('${A}', 'v1'), ('${A}', 'v2'), ('${B}', 'v1');
    insert into public.scores(user_id, points) values ('${A}', 20), ('${B}', 10);`);
  return db;
}
const count = async (db, sql) => (await db.query(sql)).rows[0].n;

async function main() {
  // 1) Ca live: NO ACTION, nume necunoscut -> ștergerea eșuează înainte, reușește după.
  for (const namedLikeLive of [true, false]) {
    const db = await schema('', { namedLikeLive });
    await assert.rejects(db.exec(`delete from auth.users where id = '${A}'`), /violates foreign key/, 'Live-like schema must refuse the delete');
    await db.exec(migration);
    await db.exec(`delete from auth.users where id = '${A}'`);
    assert.equal(await count(db, `select count(*)::int as n from public.events where user_id = '${A}'`), 0, 'Events cascade');
    assert.equal(await count(db, `select count(*)::int as n from public.scores where user_id = '${A}'`), 0, 'Scores cascade');
    assert.equal(await count(db, `select count(*)::int as n from public.events where user_id = '${B}'`), 1, "Other users' events are untouched");
    assert.equal(await count(db, `select points as n from public.scores where user_id = '${B}'`), 10, "Other users' scores are untouched");
    assert.equal(await count(db, `select count(*)::int as n from pg_constraint where conrelid in ('public.events'::regclass,'public.scores'::regclass) and contype='f'`), 2, 'Exactly one FK per table');

    // 2) Reaplicare: idempotentă.
    await db.exec(migration);
    assert.equal(await count(db, `select count(*)::int as n from pg_constraint where conrelid in ('public.events'::regclass,'public.scores'::regclass) and contype='f' and confdeltype='c'`), 2);
  }

  // 3) Schemă nouă (deja cascade): nu face nimic și nu strică nimic.
  const fresh = await schema('on delete cascade', { namedLikeLive: true });
  await fresh.exec(migration);
  assert.equal(await count(fresh, `select count(*)::int as n from public.events`), 3, 'No rows touched');

  console.log('FK cascade: live-like delete fails before and works after; other users untouched; idempotent; no-op on a cascade schema.');
}

main().catch((error) => { console.error(error); process.exitCode = 1; });
